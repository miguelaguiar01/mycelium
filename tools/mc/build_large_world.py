"""Build a large natural world and two played copies of it, for measure_merge.py.

The base world is a square of whole regions of natural terrain in one dimension, generated by
forcing one region at a time. Each copy is then loaded region by region, and the game changes
every chunk of it: one block per chunk, a container in some, the same block on both sides in some
(a true conflict), and a few seconds of ticking. So the two copies are the worst case for the
merge tool: every chunk of the dimension differs from the base on both sides.

    python3 tools/mc/build_large_world.py [--dimension overworld|nether|end] [--regions 8] [base|ours|theirs ...]

Writes .mc/runs/large-<dimension>-base, -ours and -theirs. Takes a few seconds per region.
"""

from __future__ import annotations

import argparse
import shutil
import time

from mcserver import MC_HOME, Server
from scenariolib import FAILED, fork

RUNS = MC_HOME / "runs"
# Chunk writes are not synced one by one: this world is rebuilt from scratch if a build is cut short.
PROPERTIES = {"sync-chunk-writes": "false"}
SERVER_MEMORY = "8G"
TICKS = 100
# Dimension id, and the height of the edits: above the terrain in the overworld, inside it elsewhere.
DIMENSIONS = {"overworld": ("minecraft:overworld", 200), "nether": ("minecraft:the_nether", 64),
              "end": ("minecraft:the_end", 64)}


def run_dir(dimension: str, part: str):
    return RUNS / f"large-{dimension}-{part}"


def region_chunks(rx: int, rz: int) -> list[tuple[int, int]]:
    return [(cx, cz) for cz in range(rz * 32, rz * 32 + 32) for cx in range(rx * 32, rx * 32 + 32)]


def force_region(server: Server, dimension: str, rx: int, rz: int, timeout: float = 3600) -> None:
    """Force the 1,024 chunks of a region and wait for them. One command may force at most 256."""
    inside = f"execute in {DIMENSIONS[dimension][0]}"
    for qx in range(2):
        for qz in range(2):
            x, z = (rx * 32 + qx * 16) * 16, (rz * 32 + qz * 16) * 16
            server.run(f"{inside} run forceload add {x} {z} {x + 255} {z + 255}")
    chunks = region_chunks(rx, rz)
    commands = [f"{inside} if loaded {cx * 16} 0 {cz * 16}" for cx, cz in chunks]
    deadline = time.monotonic() + timeout
    while sum("Test passed" in line for line in server.run(*commands)) != len(chunks):
        if time.monotonic() > deadline:
            raise TimeoutError(f"region {rx},{rz} did not load")
        time.sleep(0.5)


def release(server: Server, dimension: str) -> None:
    server.run(f"execute in {DIMENSIONS[dimension][0]} run forceload remove all")


def edits(dimension: str, side: str, cx: int, cz: int) -> list[str]:
    """What one side does in one chunk."""
    x, z = cx * 16, cz * 16
    y = DIMENSIONS[dimension][1]
    ours = side == "ours"
    blocks = [f"{x + 3} {y} {z + 3} minecraft:gold_block" if ours else f"{x + 12} {y} {z + 12} minecraft:iron_block"]
    if cx % 8 == 0 and cz % 8 == 0:
        # Both sides put a different block in the same place.
        blocks.append(f"{x + 8} {y + 1} {z + 8} minecraft:{'diamond' if ours else 'emerald'}_block")
    if cx % 8 == 4 and cz % 8 == 4:
        blocks.append(
            f"{x + 5} {y} {z + 5} minecraft:chest{{Items:[{{Slot:0b,id:\"minecraft:bread\",count:{1 + cx % 60}}}]}}"
            if ours else
            f"{x + 10} {y} {z + 10} minecraft:barrel{{Items:[{{Slot:3b,id:\"minecraft:coal\",count:{1 + cz % 60}}}]}}")
    return [f"execute in {DIMENSIONS[dimension][0]} run setblock {block}" for block in blocks]


def generate(dimension: str, regions: int) -> None:
    run = run_dir(dimension, "base")
    if run.exists():
        shutil.rmtree(run)
    started = time.monotonic()
    with Server(run, PROPERTIES, memory=SERVER_MEMORY) as server:
        for rz in range(regions):
            for rx in range(regions):
                force_region(server, dimension, rx, rz)
                release(server, dimension)
            print(f"  base: row {rz} done after {time.monotonic() - started:.0f} s", flush=True)
        server.save()
    print(f"{dimension} base: {regions * regions * 1024} chunks in {time.monotonic() - started:.0f} s", flush=True)


def play_copy(dimension: str, side: str, regions: int) -> None:
    run = run_dir(dimension, side)
    fork(run_dir(dimension, "base"), run)
    started = time.monotonic()
    with Server(run, PROPERTIES, memory=SERVER_MEMORY) as server:
        for rz in range(regions):
            for rx in range(regions):
                force_region(server, dimension, rx, rz)
                commands = [command for cx, cz in region_chunks(rx, rz) for command in edits(dimension, side, cx, cz)]
                bad = [line for line in server.run(*commands) if FAILED.search(line.split("]: ", 1)[-1])]
                if bad:
                    raise RuntimeError(f"{side}: commands failed in region {rx},{rz}:\n" + "\n".join(bad[:10]))
                server.sprint(TICKS)
                release(server, dimension)
            print(f"  {side}: row {rz} done after {time.monotonic() - started:.0f} s", flush=True)
        server.save()
    print(f"{dimension} {side}: played in {time.monotonic() - started:.0f} s", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dimension", choices=sorted(DIMENSIONS), default="overworld")
    parser.add_argument("--regions", type=int, default=8, help="regions per side of the square")
    parser.add_argument("parts", nargs="*", default=["base", "ours", "theirs"])
    args = parser.parse_args()
    if "base" in args.parts:
        generate(args.dimension, args.regions)
    for side in ("ours", "theirs"):
        if side in args.parts:
            play_copy(args.dimension, side, args.regions)


if __name__ == "__main__":
    main()
